	setScrollFactor('sprite1', 1, 1)
	scaleObject('sprite1', 2.2, 2.3)
	setProperty('sprite1.antialiasing', false)
	setProperty('sprite1.alpha', 1)
	setProperty('sprite1.angle', 0)
